import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const stripExports = (src) => src
  .replace(/^export\s+function\s+/gm, 'function ')
  .replace(/^export\s+const\s+/gm, 'const ');

const stylesSrc = stripExports(fs.readFileSync(path.join(rootDir, 'src', 'client', 'styles.js'), 'utf8'));
const clientSrc = fs.readFileSync(path.join(rootDir, 'src', 'client', 'index.js'), 'utf8');

const banner = [
  '// @oxmumu3/dot-memory — DSH Browser Client Bundle (generated by scripts/build-client.mjs).',
  '// Wrapped in window.__ModuleLoader__.load; zero ESM export statements.',
  '',
  'window.__ModuleLoader__.load({',
  "  id: '@oxmumu3/dot-memory',",
  '  factory: (require) => {',
  "    'use strict';",
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  '',
].join('\n');

const footer = [
  '',
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n');

const output = `${banner}${stylesSrc}\n${clientSrc}${footer}`;
if (/^\s*export\s+/m.test(output)) {
  throw new Error('dist/client.js must not contain ESM export statements');
}

fs.mkdirSync(path.join(rootDir, 'dist'), { recursive: true });
fs.writeFileSync(path.join(rootDir, 'dist', 'client.js'), output, 'utf8');
console.log(`Built dist/client.js (${Buffer.byteLength(output, 'utf8')} bytes)`);
